#!/usr/bin/env python3
"""Turn a firmware binary into rtl/cmp/boot_rom.sv (a case-statement ROM).

A case-statement ROM needs no $readmemh path, so the same file works in
every simulator and in synthesis (Yosys turns it into constant logic).
"""
import argparse
import pathlib
import struct


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("bin", type=pathlib.Path)
    ap.add_argument("out", type=pathlib.Path)
    ap.add_argument("--hex", type=pathlib.Path, help="also write a $readmemh file")
    args = ap.parse_args()

    data = args.bin.read_bytes()
    data += b"\0" * (-len(data) % 4)
    words = list(struct.unpack(f"<{len(data) // 4}I", data))

    lines = [
        "// boot_rom.sv - GENERATED by scripts/gen_rom.py from the firmware. Do not edit.",
        f"// {len(words)} words used.",
        "module boot_rom #(",
        "  parameter int WORDS = 1024",
        ") (",
        "  input  logic [$clog2(WORDS)-1:0] addr,",
        "  output logic [31:0]              data",
        ");",
        "  always_comb begin",
        "    case (32'(addr))",
    ]
    lines += [f"      {i}: data = 32'h{w:08x};" for i, w in enumerate(words) if w != 0]
    lines += [
        "      default: data = 32'h00000000;",
        "    endcase",
        "  end",
        "endmodule",
        "",
    ]
    args.out.write_text("\n".join(lines), newline="\n")
    if args.hex:
        args.hex.write_text("".join(f"{w:08x}\n" for w in words), newline="\n")
    print(f"gen_rom: {len(words)} words ({len(data)} bytes) -> {args.out}")


if __name__ == "__main__":
    main()
